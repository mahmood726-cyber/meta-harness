"""Protocol panel contracts using held benchmark inputs, never invented findings."""
import hashlib
import json
from pathlib import Path
from unittest.mock import patch

import pytest

from scripts import seed_comparator_panels as seed

REPO = Path(__file__).resolve().parents[1]
SLUG = "daratumumab-rrmm-pfs-bench"


def fixture_root(tmp_path):
    topic = (REPO / "topics" / (SLUG + ".json")).read_bytes()
    config = json.loads(topic)
    registry = json.loads((REPO / "registry/benchmarks/candidates_v1_1.json").read_bytes())
    row = next(r for r in registry["screened"] if r.get("pmid") == config["comparator_pmid"])
    for rel, raw in [(f"topics/{SLUG}.json", topic),
                     ("registry/benchmarks/candidates_v1_1.json", json.dumps({"screened": [row]}).encode()),
                     (f"cache/benchmarks/v1/{row['pmcid']}.xml", (REPO / f"cache/benchmarks/v1/{row['pmcid']}.xml").read_bytes())]:
        p = tmp_path / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(raw)
    return config, topic


def test_from_protocol_without_review(tmp_path, monkeypatch):
    config, topic = fixture_root(tmp_path)
    monkeypatch.setattr(seed, "ROOT", tmp_path)
    with patch("subprocess.check_output", return_value=topic):
        seed.main(["--slug", SLUG, "--from-protocol"])
    panel = json.loads((tmp_path / f"cache/{SLUG}/comparators.json").read_bytes())
    assert panel[0]["comparator_pmid"] == config["comparator_pmid"]
    seed.validate(panel[0], tmp_path)
    assert not (tmp_path / f"docs/reviews/{SLUG}/review.json").exists()


def test_required_field_refusal(tmp_path, monkeypatch):
    config, _ = fixture_root(tmp_path)
    del config["comparator_pmid"]
    topic = json.dumps(config).encode()
    (tmp_path / f"topics/{SLUG}.json").write_bytes(topic)
    monkeypatch.setattr(seed, "ROOT", tmp_path)
    with patch("subprocess.check_output", return_value=topic):
        with pytest.raises(ValueError, match="PROTOCOL_PANEL: required comparator_pmid"):
            seed.main(["--slug", SLUG, "--from-protocol"])
    assert not (tmp_path / f"cache/{SLUG}/comparators.json").exists()


def test_default_bytes_unchanged(tmp_path, monkeypatch):
    # The baseline is generated by the unmodified legacy producer before implementation.
    baseline = REPO / ".codex_logs/panel_legacy_fixture"
    import shutil
    shutil.copytree(baseline, tmp_path, dirs_exist_ok=True)
    expected = (tmp_path / f"cache/{SLUG}/comparators.json").read_bytes()
    monkeypatch.setattr(seed, "ROOT", tmp_path)
    original = seed.validate
    monkeypatch.setattr(seed, "validate", lambda c: original(c, tmp_path))
    monkeypatch.setattr("sys.argv", ["seed_comparator_panels.py"])
    seed.main()
    assert (tmp_path / f"cache/{SLUG}/comparators.json").read_bytes() == expected
