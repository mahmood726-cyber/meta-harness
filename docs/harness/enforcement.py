"""V15-C enforcement (Mahmood, 13 Oct, ruling 1: "then switch enforcement on").

Until now `target_endpoint.admit_rows` admitted a row with no endpoint class as UNBOUND_LEGACY: a migration state that
was pooled (bundle limits L10 / L15). With enforcement on, such a row stays in the pool ONLY under a signed ADMIT
decision (registry/v15c_decisions.json, generated by scripts/v15c_decisions.py from the recorded panel reads) whose
served-number snapshot still equals the row's numbers. A signed REFUSE, or a signed ADMIT whose numbers moved after
signing, leaves the pool and is displayed, never deleted. A row the signed decisions do not name is OUTSIDE the signed
scope: it keeps its legacy state, marked PENDING_TRIAGE, until its own panel read and signature (refusing it would move a
pool nobody signed).

Applied in harness/pipeline.py right after admit_rows; harness/target_endpoint.py is frozen (registry/regex_freeze.json).
"""
from __future__ import annotations

import json
import os
from typing import Any

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DECISIONS = os.path.join(ROOT, "registry", "v15c_decisions.json")
PACKET_SHA256 = "6067c4f1fdb5bda59b481004b6fdd5e0edb63159bbb965d17af28971e7508913"
SERVED_KEYS = ("effect", "ci_low", "ci_high", "ai", "n1i", "ci", "n2i")
UNBOUND = "UNBOUND_LEGACY"
_CACHE: dict[str, Any] = {}


def _key(slug, outcome, rid):
    return (str(slug), str(outcome), str(rid))


class EnforcementError(RuntimeError):
    pass


def decisions(path: str = DECISIONS) -> dict:
    """{(slug, outcome, id): decision}. The switch is ON: a missing file, or one that is not the signed one, STOPS the
    build -- with out-of-scope rows kept PENDING, a bad file would otherwise switch enforcement off without a word."""
    if path in _CACHE:
        return _CACHE[path]
    if not os.path.exists(path):
        raise EnforcementError(f"V15-C decisions file missing: {path}")
    doc = json.load(open(path, encoding="utf-8"))
    sig = doc.get("signed") or {}
    if sig.get("packet_sha256") != PACKET_SHA256 or sig.get("state") != "SEEN_AND_SIGNED":
        raise EnforcementError("V15-C decisions file is not the signed one (packet sha256 / state differ)")
    out = {_key(r["slug"], r["outcome"], r["id"]): r for r in doc.get("rows") or []}
    _CACHE[path] = out
    return out


def _served(t: dict) -> dict:
    out = {}
    for k in SERVED_KEYS:
        v = t.get(k)
        if v is None:
            continue
        try:
            out[k] = round(float(v), 6)
        except (TypeError, ValueError):
            out[k] = v
    return out


def _absent(t: dict, why: str, kind: str, d: dict | None) -> dict:
    refused = {k: t.get(k) for k in SERVED_KEYS + ("scale",) if t.get(k) is not None}
    base = {"label": t.get("label"), "id": t.get("id"), "source": t.get("source", ""), "provenance": t.get("provenance"),
            "endpoint_binding": t.get("endpoint_binding"), "reason": why,
            "enforcement": {"decision": (d or {}).get("decision"), "basis": (d or {}).get("basis"),
                            "recommendation": (d or {}).get("recommendation"), "readers": (d or {}).get("readers"),
                            "signed": "v15c (packet sha256 " + PACKET_SHA256[:12] + "...)"}}
    if kind == "refused_on_evidence":
        return dict(base, absent_kind="refused_on_evidence", state="REFUSED_ON_EVIDENCE",
                    reason_code="RESULT_INCOMPATIBLE", endpoint_admissibility="RESULT_INCOMPATIBLE",
                    refused_effect=refused)
    return dict(base, absent_kind="machine_absent", state="EXTRACTION_DEBT", reason_code="ENDPOINT_UNBOUND",
                endpoint_admissibility="ENDPOINT_UNBOUND", candidate_tuple=refused, refused_effect=refused,
                recovery="a reviewer binds the tuple to one span of an open held source (recorded, source-linked), and "
                         "a signed decision admits it")


def apply(slug: str, spec: dict, trials: list[dict], path: str = DECISIONS) -> tuple[list[dict], list[dict]]:
    """(kept, absent): every UNBOUND_LEGACY row is admitted only by a signed ADMIT whose snapshot equals its numbers."""
    dec = decisions(path)
    kept, absent = [], []
    for t in trials:
        if t.get("endpoint_admissibility") != UNBOUND:
            kept.append(t)
            continue
        d = dec.get(_key(slug, spec.get("name"), t.get("id")))
        if d is None:
            # OUTSIDE THE SIGNED SCOPE (the packet named 77 rows on main 66219d315): no panel has read this row, so it is
            # neither refused (a pool move nobody signed) nor admitted (a signature it lacks). It keeps its legacy
            # state, marked PENDING, until read and signed.
            t["enforcement"] = {"decision": "PENDING_TRIAGE",
                                "basis": "an unbound row outside the signed V15-C scope: awaiting its panel read and "
                                         "signature; served in its pre-enforcement (UNBOUND_LEGACY) state meanwhile"}
            kept.append(t)
            continue
        if d.get("decision") == "ADMIT":
            snap = {k: round(float(v), 6) for k, v in (d.get("served") or {}).items()}
            if snap and snap == _served(t):
                t["endpoint_admissibility"] = "SIGNED_BINDING"
                t["endpoint_binding"] = "signed_panel_binding"
                t["endpoint_binding_reason"] = d.get("basis")
                if d.get("span") and not t.get("endpoint_result_span"):
                    t["endpoint_result_span"] = d["span"]
                t["enforcement"] = {"decision": "ADMIT", "basis": d.get("basis"), "readers": d.get("readers")}
                kept.append(t)
                continue
            absent.append(_absent(t, "the row's numbers are not the numbers the signed decision admitted "
                                     f"({_served(t)} != {snap}): refused until re-signed", "abstain", d))
            continue
        absent.append(_absent(t, "signed refusal (V15-C): " + str(d.get("basis")), d.get("kind") or "abstain", d))
    return kept, absent
